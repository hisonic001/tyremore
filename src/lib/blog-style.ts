import { OWNER_SLOT } from "./blog-draft-core";

/** 네이버 블로그 편집기는 마크다운을 렌더링하지 않는다 — 붙여넣으면 기호가 그대로 찍힌다 */
const MD_HEADING = /^#{1,6}\s/m;
const MD_TABLE = /^\s*\|.*\|/m;
const MD_CHECK = /^\s*[-*]\s*\[[ xX]\]/m;
const MD_FENCE = /```/;
const MD_BULLET = /^\s*[-*+]\s+\S/m;

/**
 * 글이 「일반론」으로 시작하는지 — 사건 대신 계절·날씨·훈계로 여는 버릇.
 * 첫 60자만 본다 (사장님 글은 전부 차종·손님·상황으로 시작한다).
 */
const OPENER_FILLER =
  /^[^\n]{0,60}?(여름|겨울|봄철?|가을|장마|무더위|한파|날씨|계절|환절기|요즘)[^\n]{0,20}?(이|가|은|는)?\s*(끝나|시작|다가|바뀌|접어들|되면|에는|이면)/;

/** 사장님 글에 없는 설명체·상투구 — 하나만 있으면 넘어가되 여러 개면 티가 난다 */
const CLICHES = [
  "좋은 시기입니다",
  "중요합니다",
  "말씀드리는 편입니다",
  "하는 것이 좋습니다",
  "잊지 마시기 바랍니다",
  "도움이 되셨길",
  "안전 운전 하세요",
  "라고 할 수 있습니다",
  "필수적입니다",
  "핵심입니다",
];

/** 주행거리를 뭉갠 표현 — 이제 정확한 km 를 주므로 나오면 안 된다 */
const VAGUE_KM = /\d+\s*만\s*km\s*대/;

export interface StyleProblem {
  /** 사장님이 읽을 한 줄 */
  reason: string;
  /** 모델에게 되돌려 줄 지적 — 재시도 지시문에 붙는다 */
  fix: string;
}

/**
 * 나온 글이 「사장님 글」처럼 생겼는지 본다. 문제가 있으면 그 이유를 돌려준다.
 * 🔴 통과 못 하면 버리고 다시 쓴다 (privacyFilter 와 같은 자리에서 돈다).
 */
export function styleFilter(body: string): StyleProblem | null {
  if (MD_HEADING.test(body) || MD_FENCE.test(body)) {
    return {
      reason: "마크다운 소제목(#)이 들어갔습니다 — 네이버에 붙이면 기호가 그대로 나옵니다",
      fix: "소제목은 '#' 없이 평범한 한 줄로 쓰세요. 마크다운 기호를 전혀 쓰지 마세요.",
    };
  }
  if (MD_TABLE.test(body)) {
    return {
      reason: "표(|)가 들어갔습니다 — 네이버 블로그는 마크다운 표를 못 그립니다",
      fix: "표를 쓰지 마세요. 표로 정리하고 싶은 내용은 문장이나 줄바꿈으로 풀어 쓰세요.",
    };
  }
  if (MD_CHECK.test(body) || MD_BULLET.test(body)) {
    return {
      reason: "체크리스트·불릿 기호가 들어갔습니다 — 기호가 그대로 찍힙니다",
      fix: "'-' 나 '- [ ]' 같은 기호를 쓰지 마세요. 나열은 줄바꿈으로만 하세요.",
    };
  }
  if (VAGUE_KM.test(body)) {
    return {
      reason: "주행거리를 「N만km대」로 뭉갰습니다 — 준 그대로 정확히 써야 믿음이 갑니다",
      fix: "주행거리는 주어진 정확한 숫자를 그대로 쓰세요 (예: 126,726km).",
    };
  }

  /** 줄이 길면 폰에서 안 읽힌다. 사장님 글은 평균 19~21자다 */
  const lines = body.split("\n").filter((l) => l.trim().length > 0);
  if (lines.length >= 8) {
    const avg = lines.reduce((s, l) => s + l.length, 0) / lines.length;
    if (avg > 45) {
      return {
        reason: `줄이 너무 깁니다 (평균 ${Math.round(avg)}자) — 사장님 글은 20자 안팎으로 끊어 씁니다`,
        fix: "한 줄을 25자 안팎에서 끊어 쓰세요. 문단 사이에는 빈 줄을 넣으세요. 폰에서 읽는 글입니다.",
      };
    }
  }

  if (OPENER_FILLER.test(body)) {
    return {
      reason: "계절·날씨 이야기로 시작했습니다 — 사장님 글은 늘 그날의 일로 시작합니다",
      fix: "첫 문장은 그 차와 그날 있었던 일로 시작하세요. 계절·날씨·일반론으로 열지 마세요.",
    };
  }

  const hits = CLICHES.filter((c) => body.includes(c));
  if (hits.length >= 2) {
    return {
      reason: `상투적인 표현이 겹쳤습니다 (${hits.slice(0, 3).join(", ")})`,
      fix: `다음 표현을 쓰지 마세요: ${hits.join(", ")}. 겪은 일을 그대로 말하듯 쓰세요.`,
    };
  }

  /**
   * 🔴 **소제목이 있어야 훑을 수 있다** (2026-09-04 개정).
   *
   *    실측으로 알게 된 것: **블로그에 실린 글은 이미 소제목을 4~7개 쓰고 있다**
   *    (`수치로 확인한 원인` · `0.1mm 단위 교정` · `토크렌치 175 Nm 정토크 마무리`).
   *    문제는 **앱이 만든 원고**였다 — 11건 중 4건이 소제목 0개였다.
   *    그래서 이 검사는 「없던 걸 만드는」 게 아니라 **블로그 수준을 지키는 자물쇠**다.
   *
   *    한 줄이 20자로 균일한 글이라, 「앞뒤가 **모두** 빈 줄 + 짧고 + 서술어 없이 끝나는 줄」
   *    만 소제목으로 센다. 앞만 보면 문단 첫 줄이 전부 걸린다.
   */
  const subs = countSubheads(body);
  if (subs < 4) {
    return {
      reason: `소제목이 ${subs}개뿐입니다 — 폰에서 훑어볼 덩어리가 없습니다`,
      fix: "작업 순서대로 소제목을 4~6개 넣으세요. 각 소제목은 10~20자로 짧게, 서술어 없이 끊고(예: 「기존 타이어 상태 확인」), 앞뒤에 빈 줄을 두세요. 기호는 쓰지 마세요.",
    };
  }

  /** 끝까지 안 읽는 사람이 가져갈 것 — 이 블록이 없으면 훑는 사람에게 남는 게 없다 */
  if (!SUMMARY_BLOCK.test(body)) {
    return {
      reason: "「오늘 정리」 블록이 없습니다 — 끝까지 안 읽는 분이 가져갈 것이 없습니다",
      fix: "글 뒤쪽에 「오늘 정리」라는 한 줄을 두고, 그 아래 3~5줄로 규격·수치·다음 점검 시점만 적으세요.",
    };
  }

  return null;
}

/** 「오늘 정리」 요약 블록 */
const SUMMARY_BLOCK = /^\s*오늘\s*정리\s*$/m;

/**
 * 소제목 세기 — **앞뒤가 빈 줄이고, 짧고, 서술어로 끝나지 않는 줄**.
 * 🔴 판정 규칙은 여기 한 곳에만 둔다. 화면·검사·재는 자(scripts/blog-measure.ts)가 같이 쓴다.
 */
export function countSubheads(body: string): number {
  return subheads(body).length;
}

export function subheads(body: string): string[] {
  const raw = body.split("\n");
  const out: string[] = [];
  for (let i = 0; i < raw.length; i++) {
    const s = raw[i].trim();
    if (s.length < 6 || s.length > 24) continue;
    /* 사진·영상 자리표시자와 해시태그는 소제목이 아니다 */
    if (/^[[#※━]/.test(s)) continue;
    /**
     * 🔴 `{{사장님_한마디}}` 같은 자리표시자도 아니다.
     *    이걸 안 빼면 **소제목이 하나도 없는 원고가 1개로 세어진다** (실측: 11건 중 4건).
     */
    if (/^\{\{.*\}\}$/.test(s)) continue;
    /* 서술어로 끝나면 본문 문장이다 */
    if (/(니다|습니다|세요|해요|였다|이다|한다|\.|!|\?)$/.test(s)) continue;
    /**
     * 🔴 **앞뒤가 모두 빈 줄**이어야 소제목이다.
     *    앞만 보면 문단 첫 줄이 소제목으로 잡힌다 — 이 블로그는 한 줄이 20자라
     *    `타이어를 새로 교체하셨는데` 같은 **문장 앞토막**이 전부 걸려 버린다.
     *    혼자 떨어져 서 있어야 폰에서도 덩어리로 보인다.
     */
    const before = (raw[i - 1] ?? "").trim();
    const after = (raw[i + 1] ?? "").trim();
    if (before === "" && after === "") out.push(s);
  }
  return out;
}

